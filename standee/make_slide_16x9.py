#!/usr/bin/env python3
"""Render the 16:9 slide template into one ``*.src.html`` per language.

    slide-16x9.template.html  +  slide-16x9-copy.json  ->  visemi-slide-16x9-{en,vi}.src.html

Those generated sources are then picked up by ``build_standee.py``'s existing glob
and inlined into self-contained HTML exactly like the standee's own source, so this
script adds a step in front of the pipeline rather than a second pipeline.

WHY a generator rather than two sibling sources. The two standee print masters do
duplicate ~350 lines of markup, and DESIGN.md accepts that because they differ in
GEOMETRY: two page boxes, two vertical rhythms, two chip-band bakes. The two
language versions of this slide differ in COPY. Duplicated geometry is annoying;
duplicated copy is the kind that rots, because the failure mode is silent - someone
fixes a line in one file, the other keeps the old wording, and nothing complains.
So the template owns the layout, the JSON owns every string, and the three values
that a string can force (headline size, CTA qualifier size, which language of the
Cat Canh lockup) are per-language entries in the JSON rather than magic in here.

The generated files carry a DO NOT EDIT banner. Editing one is not caught by any
check, it is simply overwritten on the next run, so the banner is the only warning
there is.

    uv run --project .. python make_slide_16x9.py              # sources only
    uv run --project .. python make_slide_16x9.py --render     # sources -> every deliverable
    uv run --project .. python make_slide_16x9.py --self-test

``--render`` carries the whole chain: generate the sources, inline them with
``build_standee.py``, screenshot each language to a 2x PNG, print each to PDF, and
hand each to ``scripts/ops/html_to_pptx.py``. It exists because that is nine commands
run in a fixed order, it has to be re-run after every copy edit, and doing it by hand
means the day someone forgets one step a stale PNG or PDF ships next to a fresh one.
That already happened once: the PDFs were printed before a card merge and were a
revision behind the PNGs until the mismatch was spotted by timestamp.

Two hazards in that chain are handled here rather than left to the caller, because
both fail quietly:

  * ``--hide-scrollbars`` on the screenshot. Without it Chrome reserves gutter and
    the PNG comes back short of its nominal width with the right edge clipped.
  * an absolute ``--print-to-pdf`` path and a per-invocation ``--user-data-dir``.
    With a relative path or a shared profile Chrome writes nothing and still exits 0.

It deliberately does NOT run ``check_standee.py``. That gate measures the built PDFs
and needs the working repo's ``pypdfium2``, so it has to run from the repo root
rather than under ``--project ..``; the command is printed at the end instead.

Vietnamese is written through vn_json's sibling rule: read and write with an
explicit encoding="utf-8" everywhere. On Windows a bare open() goes through the
ANSI codepage and replaces every Vietnamese diacritic with "?", irreversibly, while
leaving a file that still looks like valid HTML. verify() below re-reads what was
written and fails on that signature rather than trusting it.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / "slide-16x9.template.html"
COPY = HERE / "slide-16x9-copy.json"
STEM = "visemi-slide-16x9"

TOKEN = re.compile(r"\{\{([a-z0-9_]+)\}\}")

# The slide's CSS pixel box, which is also the screenshot viewport.
DEFAULT_LANGS = ("en", "vi")
SLIDE_PX = (1280, 720)
PNG_SCALE = 2

CHROMES = (
    Path(r"C:\Program Files\Google\Chrome\Application\chrome.exe"),
    Path(r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe"),
)

# HERE is <working repo>/visual-generation/standee, so parents[1] is the working repo
# root. This folder is already coupled to it - build_standee.py imports the onsemi
# pitch deck's inliner from there - so reaching for the repo's own scripts/ops is the
# existing pattern, not a new dependency. It is still resolved defensively: this
# submodule is consumed by repos that have no scripts/ops at all, and there the pptx
# step should skip with a message rather than crash the whole render.
REPO = HERE.parents[1]
PPTX_SCRIPT = REPO / "scripts/ops/html_to_pptx.py"


BANNER = (
    "<!-- GENERATED by make_slide_16x9.py from slide-16x9.template.html +\n"
    "     slide-16x9-copy.json. DO NOT EDIT: edit those two and re-run. Any change\n"
    "     made here is overwritten on the next build and nothing will warn you. -->\n"
)


def languages(spec: dict) -> dict[str, dict]:
    """Every top-level key that is not a leading-underscore note is a language."""
    return {k: v for k, v in spec.items() if not k.startswith("_")}


def render(template: str, values: dict[str, str]) -> str:
    """Substitute every {{token}}, and fail loudly on a token with no value.

    A missing key must be an error, not an empty string: an unfilled headline would
    render as a blank line that looks like a design decision.
    """
    missing: list[str] = []

    def sub(m: re.Match[str]) -> str:
        key = m.group(1)
        if key not in values:
            missing.append(key)
            return m.group(0)
        return str(values[key])

    out = TOKEN.sub(sub, template)
    if missing:
        raise KeyError(f"template tokens with no value in the copy file: {sorted(set(missing))}")
    return out


def verify(text: str, lang: str) -> None:
    """Catch the two ways a generated file can be quietly wrong."""
    left = TOKEN.search(text)
    if left:
        raise AssertionError(f"{lang}: token {left.group(0)} survived rendering")
    # Diacritics flattened to "?" by an ANSI write. A real file of ours has many
    # non-ASCII bytes and few literal question marks; a mangled one has the reverse,
    # so this needs no tuned threshold.
    non_ascii = sum(1 for c in text if ord(c) > 127)
    if text.count("?") > 4 and non_ascii < 20:
        raise AssertionError(
            f"{lang}: {text.count('?')} literal '?' against only {non_ascii} non-ASCII "
            f"characters, which is the signature of an ANSI-codepage write destroying "
            f"the diacritics"
        )
    if lang == "vi" and "Cất Cánh" not in text:
        raise AssertionError("vi: 'Cất Cánh' missing or its diacritics were destroyed")
    for dash in ("—", "–"):
        if dash in text:
            raise AssertionError(f"{lang}: contains {dash!r}, house rule forbids em/en dashes")


def build() -> None:
    template = TEMPLATE.read_text(encoding="utf-8")
    spec = json.loads(COPY.read_text(encoding="utf-8"))
    for lang, values in languages(spec).items():
        html = BANNER + render(template, values)
        verify(html, lang)
        out = HERE / f"{STEM}-{lang}.src.html"
        out.write_text(html, encoding="utf-8")
        # Prove it on the way back out, not on the way in: the write is where the
        # codepage damage happens.
        verify(out.read_text(encoding="utf-8"), lang)
        print(f"{out.name}  {len(html) / 1e3:.1f} KB")


def find_chrome(override: str | None) -> Path:
    if override:
        p = Path(override)
        if not p.is_file():
            sys.exit(f"no chrome at {p}")
        return p
    for p in CHROMES:
        if p.is_file():
            return p
    sys.exit("Chrome not found; pass --chrome PATH")


def _run(cmd: list[str], what: str, cwd: Path | None = None) -> None:
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              encoding="utf-8", errors="replace",
                              cwd=str(cwd) if cwd else None)
    except FileNotFoundError:
        sys.exit(f"{what} failed: {cmd[0]!r} not on PATH")
    if proc.returncode != 0:
        sys.exit(f"{what} failed ({proc.returncode}):\n{proc.stdout}\n{proc.stderr}")
    for line in (proc.stdout or "").splitlines():
        if line.strip():
            print(f"    {line}")


def chrome_png(chrome: Path, html: Path, png: Path, profile: str) -> None:
    """Screenshot at PNG_SCALE. --hide-scrollbars is load-bearing, see the module
    docstring."""
    w, h = SLIDE_PX
    _run([str(chrome), "--headless=new", "--disable-gpu", "--hide-scrollbars",
          f"--user-data-dir={Path(tempfile.gettempdir()) / profile}",
          f"--window-size={w},{h}", f"--force-device-scale-factor={PNG_SCALE}",
          "--virtual-time-budget=9000", f"--screenshot={png.resolve()}",
          html.resolve().as_uri()], f"screenshot {png.name}")
    if not png.is_file():
        sys.exit(f"Chrome wrote no screenshot at {png}")


def chrome_pdf(chrome: Path, html: Path, pdf: Path, profile: str) -> None:
    """Print to PDF. The path must be absolute and the profile must be this run's
    own, or Chrome writes nothing and still exits 0."""
    _run([str(chrome), "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
          f"--user-data-dir={Path(tempfile.gettempdir()) / profile}",
          "--virtual-time-budget=9000", f"--print-to-pdf={pdf.resolve()}",
          html.resolve().as_uri()], f"print {pdf.name}")
    if not pdf.is_file():
        sys.exit(f"Chrome wrote no PDF at {pdf}")


def render_all(chrome: Path, langs: list[str]) -> None:
    print("build_standee.py")
    _run([sys.executable, str(HERE / "build_standee.py")], "build_standee.py")

    for lang in langs:
        html = HERE / f"{STEM}-{lang}.html"
        if not html.is_file():
            sys.exit(f"{html.name} missing; did build_standee.py run?")
        print(f"{lang}:")
        chrome_png(chrome, html, HERE / f"{STEM}-{lang}.png", f"chrome-slide-{lang}")
        chrome_pdf(chrome, html, HERE / f"{STEM}-{lang}.pdf", f"chrome-slidepdf-{lang}")
        if PPTX_SCRIPT.is_file():
            # NOT sys.executable. This script is normally run as
            # `uv run --project .. python make_slide_16x9.py`, so sys.executable is
            # the visual-generation submodule's venv, and python-pptx lives in the
            # WORKING repo's venv. Handing the pptx step sys.executable fails with
            # ModuleNotFoundError: No module named 'pptx'. Same env boundary that
            # forces check_standee.py to run from the repo root for pypdfium2, so it
            # is crossed explicitly with `uv run --project <repo>` instead.
            _run(["uv", "run", "--project", str(REPO), "python",
                  str(PPTX_SCRIPT), "--html", str(html)],
                 f"html_to_pptx {lang}", cwd=REPO)
        else:
            print(f"    (no pptx: {PPTX_SCRIPT} not present in this checkout)")

    print("\nNot run here, because it needs the working repo's pypdfium2 to measure "
          "the PDFs:\n  uv run python visual-generation/standee/check_standee.py")


def self_test() -> None:
    template = TEMPLATE.read_text(encoding="utf-8")
    spec = json.loads(COPY.read_text(encoding="utf-8"))
    langs = languages(spec)
    assert set(langs) == {"en", "vi"}, sorted(langs)

    # Every language must supply every token the template asks for, and no language
    # may quietly carry a key the template has stopped using.
    wanted = set(TOKEN.findall(template))
    assert wanted, "template has no tokens; the substitution syntax must have changed"
    for lang, values in langs.items():
        assert wanted <= set(values), f"{lang} is missing {sorted(wanted - set(values))}"
        unused = set(values) - wanted
        assert not unused, f"{lang} has unused keys {sorted(unused)}"

    # The copy rules that matter, asserted rather than trusted. Soft hyphens are
    # stripped first: the English copy writes VISEMI Foun&shy;da&shy;tion, so a naive
    # substring check would report the brand name missing from the one place it is
    # guaranteed to be. check_standee.py strips U+00AD for the same reason.
    def plain(text: str) -> str:
        return text.replace("&shy;", "")

    # Keys that are machinery, not display copy. They are excluded from the copy
    # rules because the Cat Canh logo path really does contain the ASCII folder name
    # "Cat Canh Logo Package" as it exists on disk, and a diacritics check over
    # every value would flag that filesystem path as a house-rule violation.
    NOT_COPY = {"lang", "cc_logo", "cc_logo_w", "headline_size", "scan_qual_size"}

    def copy_values(values: dict) -> str:
        return plain(" ".join(str(v) for k, v in values.items() if k not in NOT_COPY))

    for lang, values in langs.items():
        joined = copy_values(values)
        assert "VISEMI Foundation" in plain(values["lead"]), (
            f"{lang}: lead must name VISEMI Foundation")
        for dash in ("—", "–"):
            assert dash not in joined, f"{lang}: em/en dash in the copy"
        assert "Cat Canh" not in joined, f"{lang}: 'Cat Canh' without diacritics"
    # Proper nouns stay in English inside the Vietnamese copy: house register.
    for name in ("Demystifying Semiconductors", "VISEMI Chip Chat", "Cất Cánh Pathway"):
        vi_all = copy_values(langs["vi"])
        assert name in vi_all, f"vi lost {name!r}"
    # The Fellowship is the one programme that DOES take a Vietnamese name, and it is
    # the one the logo lockup has to agree with.
    assert langs["vi"]["p3_name"] == "Học bổng Cất Cánh", langs["vi"]["p3_name"]
    assert "logo-vie" in langs["vi"]["cc_logo"] and "logo-eng" in langs["en"]["cc_logo"]

    # Every referenced asset must exist, or the build fails much later in
    # build_standee.py with a path error instead of here.
    repo = HERE.parents[1]
    for lang, values in langs.items():
        rel = values["cc_logo"]
        assert (HERE / rel).is_file() or (repo / rel).is_file(), f"{lang}: missing {rel}"
    assert (HERE / "assets/chipchat-white.png").is_file(), "missing derived Chip Chat asset"

    # render() must refuse to leave a hole rather than emit a blank.
    try:
        render("{{nope}}", {})
    except KeyError as e:
        assert "nope" in str(e), e
    else:
        raise AssertionError("render() accepted an unfilled token")

    # The two Chrome flags that fail silently must stay in the command builders.
    # Asserted on the source rather than by running Chrome, since that is the whole
    # point: a missing flag produces a plausible file, not an error.
    src = pathlib.Path(__file__).read_text(encoding="utf-8")
    png_fn = src[src.index("def chrome_png"):src.index("def chrome_pdf")]
    assert "--hide-scrollbars" in png_fn, "the screenshot must hide scrollbars"
    assert "force-device-scale-factor" in png_fn, "the screenshot must be 2x"
    pdf_fn = src[src.index("def chrome_pdf"):src.index("def render_all")]
    assert "resolve()" in pdf_fn, "--print-to-pdf needs an absolute path"
    for fn in (png_fn, pdf_fn):
        assert "user-data-dir" in fn, "each Chrome run needs its own profile"

    # The pptx step must cross the venv boundary explicitly. Handing it
    # sys.executable picks the submodule's env, which has no python-pptx.
    # Matched on the call itself, not on the surrounding text: an earlier version of
    # this assertion searched the slice for "sys.executable" and was tripped by the
    # comment that explains why sys.executable is wrong.
    chain = src[src.index("def render_all"):src.index("def self_test")]
    assert '_run(["uv", "run", "--project", str(REPO), "python",' in chain, (
        "the pptx step must cross into the working repo's env, not sys.executable")

    # render_all() must cover every language the copy file declares, so adding a
    # third language cannot silently render only two. Note the chain is render_ALL:
    # plain render() is the template substituter, and naming the chain render() once
    # made this very self-test run the build chain instead of checking substitution.
    assert set(langs) == set(DEFAULT_LANGS), (langs.keys(), DEFAULT_LANGS)

    # verify() must catch both damage modes.
    for bad, needle in ((("x {{tok}} y"), "survived"), ("V?? Ch??ng t?i n?i ??", "ANSI")):
        try:
            verify(bad, "vi")
        except AssertionError as e:
            assert needle in str(e), (bad, e)
        else:
            raise AssertionError(f"verify() passed {bad!r}")

    print("self-test ok")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--render", action="store_true",
                    help="after generating, build and render every deliverable")
    ap.add_argument("--lang", choices=DEFAULT_LANGS,
                    help="render one language only (default: both)")
    ap.add_argument("--chrome", help="path to chrome.exe")
    args = ap.parse_args()
    try:
        if args.self_test:
            self_test()
        else:
            build()
            if args.render:
                render_all(find_chrome(args.chrome),
                       [args.lang] if args.lang else list(DEFAULT_LANGS))
    except (AssertionError, KeyError) as exc:
        sys.exit(f"FAILED: {exc}")
